
import streamlit as st

st.title("ℹ️ About DzongkhaGPT")

st.markdown("""
## About the Project

DzongkhaGPT is an AI-powered chatbot designed to support
communication in English and Dzongkha.

It combines a language model with machine translation
to provide responses in both languages.

## Technologies Used

- Python
- Streamlit
- Ollama
- Gemini API
- NLLB-200 Machine Translation
- Natural Language Processing

## Main Features

- English and Dzongkha conversations
- AI-generated responses
- Machine translation
- Optional translation quality checking
- Conversation history during a session

## Purpose

The project aims to make artificial intelligence
more accessible to Dzongkha-speaking users in Bhutan.
""")
